"""Top-level Dagster definitions for the Jira SCRUM ETL pipeline.

Run locally with:
    dagster dev

Or point to this module:
    DAGSTER_MODULE_NAME=dagster_pipeline.definitions dagster dev
"""

from __future__ import annotations

import os

from dagster import Definitions, EnvVar, load_assets_from_modules
from dagster_dbt import DbtCliResource, dbt_assets

from dagster_pipeline.assets import exports, gsheets, jira
from dagster_pipeline.resources.gsheets_resource import GSheetsResource
from dagster_pipeline.resources.jira_resource import JiraResource
from dagster_pipeline.schedules import (
    cleanup_monthly_schedule,
    cleanup_old_runs_job,
    jira_sprint_closed_sensor,
    raw_jira_issues_job,
    raw_jira_issues_partition_sensor,
    team_splits_monday_schedule,
    weekly_tuesday_schedule,
    full_pipeline_job,
    extraction_only_job,
    team_splits_prepopulate_job,
    sprint_plan_update_job,
    sprint_planning_sync_job,
    capacity_inputs_sync_job,
)

import pathlib

# ─────────────────────────────────────────────────────────────────────────────
# dbt integration
# ─────────────────────────────────────────────────────────────────────────────

DBT_PROJECT_DIR = pathlib.Path(__file__).parents[1] / "dbt_project"
DBT_PROFILES_DIR = DBT_PROJECT_DIR   # profiles.yml lives alongside dbt_project.yml

dbt_resource = DbtCliResource(
    project_dir=str(DBT_PROJECT_DIR),
    profiles_dir=str(DBT_PROFILES_DIR),
)

# Load the dbt manifest (generated by `dbt parse` or `dbt compile`)
# On first run you'll need: cd dbt_project && dbt deps && dbt parse
try:
    from dagster_dbt import DbtProject

    dbt_project = DbtProject(
        project_dir=DBT_PROJECT_DIR,
        packaged_project_dir=DBT_PROJECT_DIR,
    )
    dbt_project.prepare_if_dev()

    @dbt_assets(manifest=dbt_project.manifest_path)
    def dbt_pipeline_assets(context, dbt: DbtCliResource):
        yield from dbt.cli(["build"], context=context).stream()

    _dbt_asset_list = [dbt_pipeline_assets]
except Exception as exc:
    # Graceful degradation: if the dbt manifest is not yet generated, skip dbt assets.
    # Run `cd dbt_project && dbt deps && dbt parse` to generate it.
    import warnings
    warnings.warn(
        f"dbt assets not loaded (manifest missing?). Run `dbt parse` in dbt_project/. Error: {exc}"
    )
    _dbt_asset_list = []

# ─────────────────────────────────────────────────────────────────────────────
# Python extraction assets
# ─────────────────────────────────────────────────────────────────────────────

_python_assets = load_assets_from_modules([jira, gsheets, exports])

# ─────────────────────────────────────────────────────────────────────────────
# Resources
# ─────────────────────────────────────────────────────────────────────────────

resources = {
    "jira": JiraResource(
        base_url=EnvVar("JIRA_BASE_URL"),
        email=EnvVar("JIRA_EMAIL"),
        api_token=EnvVar("JIRA_API_TOKEN"),
    ),
    "gsheets": GSheetsResource(
        credentials_path=EnvVar("GOOGLE_APPLICATION_CREDENTIALS"),
        input_spreadsheet_id=EnvVar("GSHEETS_INPUT_SPREADSHEET_ID"),
        output_spreadsheet_id=EnvVar("GSHEETS_OUTPUT_SPREADSHEET_ID"),
    ),
    "dbt": dbt_resource,
}

# ─────────────────────────────────────────────────────────────────────────────
# Top-level Definitions
# ─────────────────────────────────────────────────────────────────────────────

defs = Definitions(
    assets=[*_python_assets, *_dbt_asset_list],
    resources=resources,
    jobs=[
        full_pipeline_job,
        extraction_only_job,
        team_splits_prepopulate_job,
        raw_jira_issues_job,
        sprint_plan_update_job,
        sprint_planning_sync_job,
        capacity_inputs_sync_job,
        cleanup_old_runs_job,
    ],
    schedules=[weekly_tuesday_schedule, team_splits_monday_schedule, cleanup_monthly_schedule],
    sensors=[jira_sprint_closed_sensor, raw_jira_issues_partition_sensor],
)
